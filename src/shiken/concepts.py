@dataclass(frozen=True)
class Concepts:
    """語のリストと、文にするときの名詞。"""

    words: tuple
    noun: str
    name: str = ""

    def __post_init__(self):
        object.__setattr__(self, "words", tuple(dict.fromkeys(self.words)))

    def texts(self) -> list[str]:
        return [phrase(w, self.noun) for w in self.words]

    def to_dict(self) -> dict:
        return {"name": self.name, "noun": self.noun, "words": list(self.words)}

    @classmethod
    def from_dict(cls, d: dict) -> "Concepts":
        return cls(tuple(d["words"]), d["noun"], d.get("name", ""))


def phrase(word: str, noun: str) -> str:
    # 形容詞的な語 (「〜な」「〜の」「〜い」「〜た」) はそのまま名詞に、名詞的な語は「の」でつなぐ
    if word.endswith(("な", "の", "い", "た")):
        return f"{word}{noun}"
    return f"{word}の{noun}"


