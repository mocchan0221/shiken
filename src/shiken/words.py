def large(domain: str) -> Concepts:
    """分野 (food / art / ui / photo / face / music) の広めの辞書。"""
    base = concepts.BUILTIN[domain]
    common = COMMON_MUSIC if domain == "music" else COMMON_IMAGE
    return Concepts(tuple(common + DOMAIN_WORDS.get(domain, []) + list(base.words)), base.noun, f"{domain}-large")
